-- V1: baseline of the schema as created by Hibernate (ddl-auto: update) during development.

CREATE TABLE users (
                       id bigint GENERATED BY DEFAULT AS IDENTITY,
                       created_at timestamp(6) with time zone NOT NULL,
                       email varchar(255) NOT NULL,
                       name varchar(255) NOT NULL,
                       password_hash varchar(255),
                       auth_provider varchar(20) NOT NULL DEFAULT 'LOCAL',
                       google_id varchar(255),
                       CONSTRAINT users_pkey PRIMARY KEY (id),
                       CONSTRAINT uk6dotkott2kjsp8vw4d0m25fb7 UNIQUE (email)
);
CREATE UNIQUE INDEX ux_users_google_id ON users USING btree (google_id);

CREATE TABLE categories (
                            id bigint GENERATED BY DEFAULT AS IDENTITY,
                            name varchar(255) NOT NULL,
                            type varchar(255) NOT NULL,
                            user_id bigint,
                            CONSTRAINT categories_pkey PRIMARY KEY (id),
                            CONSTRAINT categories_type_check CHECK (type IN ('EXPENSE', 'INCOME'))
);

CREATE TABLE expense_groups (
                                id bigint GENERATED BY DEFAULT AS IDENTITY,
                                created_at timestamp(6) with time zone NOT NULL,
                                name varchar(255) NOT NULL,
                                created_by bigint NOT NULL,
                                CONSTRAINT expense_groups_pkey PRIMARY KEY (id)
);

CREATE TABLE group_members (
                               id bigint GENERATED BY DEFAULT AS IDENTITY,
                               created_at timestamp(6) with time zone NOT NULL,
                               display_name varchar(255) NOT NULL,
                               group_id bigint NOT NULL,
                               user_id bigint,
                               CONSTRAINT group_members_pkey PRIMARY KEY (id),
                               CONSTRAINT ukp940p7g0r9yihubnf6rtaheog UNIQUE (group_id, user_id)
);

CREATE TABLE group_expenses (
                                id bigint GENERATED BY DEFAULT AS IDENTITY,
                                amount numeric(12,2) NOT NULL,
                                description varchar(255) NOT NULL,
                                expense_date date NOT NULL,
                                split_type varchar(255) NOT NULL,
                                created_by bigint NOT NULL,
                                group_id bigint NOT NULL,
                                paid_by_member_id bigint NOT NULL,
                                CONSTRAINT group_expenses_pkey PRIMARY KEY (id),
                                CONSTRAINT group_expenses_split_type_check CHECK (split_type IN ('EQUAL', 'EXACT', 'PERCENTAGE'))
);

CREATE TABLE expense_splits (
                                id bigint GENERATED BY DEFAULT AS IDENTITY,
                                share_amount numeric(12,2) NOT NULL,
                                group_expense_id bigint NOT NULL,
                                member_id bigint NOT NULL,
                                CONSTRAINT expense_splits_pkey PRIMARY KEY (id)
);

CREATE TABLE expenses (
                          id bigint GENERATED BY DEFAULT AS IDENTITY,
                          amount numeric(12,2) NOT NULL,
                          created_at timestamp(6) with time zone NOT NULL,
                          expense_date date NOT NULL,
                          note varchar(255),
                          category_id bigint,
                          user_id bigint NOT NULL,
                          CONSTRAINT expenses_pkey PRIMARY KEY (id)
);

CREATE TABLE incomes (
                         id bigint GENERATED BY DEFAULT AS IDENTITY,
                         amount numeric(12,2) NOT NULL,
                         created_at timestamp(6) with time zone NOT NULL,
                         income_date date NOT NULL,
                         note varchar(255),
                         source_type varchar(255) NOT NULL,
                         category_id bigint,
                         user_id bigint NOT NULL,
                         CONSTRAINT incomes_pkey PRIMARY KEY (id),
                         CONSTRAINT incomes_source_type_check CHECK (source_type IN ('SALARY', 'OTHER'))
);

CREATE TABLE salary_settings (
                                 id bigint GENERATED BY DEFAULT AS IDENTITY,
                                 active boolean NOT NULL,
                                 amount numeric(12,2) NOT NULL,
                                 credit_day integer NOT NULL,
                                 user_id bigint NOT NULL,
                                 CONSTRAINT salary_settings_pkey PRIMARY KEY (id),
                                 CONSTRAINT ukak8pq9l38p032hbc49c2pa72t UNIQUE (user_id)
);

CREATE TABLE salary_cycles (
                               id bigint GENERATED BY DEFAULT AS IDENTITY,
                               confirmed_at timestamp(6) with time zone,
                               month date NOT NULL,
                               prompts_sent integer NOT NULL,
                               status varchar(255) NOT NULL,
                               income_id bigint,
                               user_id bigint NOT NULL,
                               credit_date date NOT NULL,
                               expected_amount numeric(12,2) NOT NULL,
                               last_prompted_on date,
                               CONSTRAINT salary_cycles_pkey PRIMARY KEY (id),
                               CONSTRAINT salary_cycles_status_check CHECK (status IN ('PENDING', 'CONFIRMED', 'MISSED')),
                               CONSTRAINT uk9xe3n4f1f4tpvd8ets5j8prg6 UNIQUE (income_id),
                               CONSTRAINT ukk5v8fhpdcgcifupws69e9lwug UNIQUE (user_id, month)
);

CREATE TABLE notifications (
                               id bigint GENERATED BY DEFAULT AS IDENTITY,
                               created_at timestamp(6) with time zone NOT NULL,
                               message varchar(255) NOT NULL,
                               is_read boolean NOT NULL,
                               type varchar(255) NOT NULL,
                               salary_cycle_id bigint,
                               user_id bigint NOT NULL,
                               CONSTRAINT notifications_pkey PRIMARY KEY (id),
                               CONSTRAINT notifications_type_check CHECK (type = 'SALARY_REMINDER')
);

CREATE TABLE settlements (
                             id bigint GENERATED BY DEFAULT AS IDENTITY,
                             amount numeric(12,2) NOT NULL,
                             settled_on date NOT NULL,
                             from_member_id bigint NOT NULL,
                             group_id bigint NOT NULL,
                             to_member_id bigint NOT NULL,
                             CONSTRAINT settlements_pkey PRIMARY KEY (id)
);

